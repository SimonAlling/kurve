import fs from "node:fs";
import path from "node:path";
import { generateTypeScript } from "elm-ts-types";

export default function postprocess({ code, targetName }) {
  const fileContent = `// Generated by elm-ts-types — do not edit manually.\n${generateTypeScript(code)}`;

  fs.writeFileSync(
    path.join(
      import.meta.dirname,
      "src",
      "typescript",
      `${targetName}.elm.d.ts`,
    ),
    fileContent,
  );

  return code;
}
